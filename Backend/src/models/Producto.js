class Producto {
    constructor(id, nombre, descripcion, precio, imagen, disponible, categoriaId) {
        this.id = id;
        this.nombre = nombre;
        this.descripcion = descripcion;
        this.precio = precio;
        this.imagen = imagen;
        this.disponible = disponible;
        this.categoriaId = categoriaId;
    }
}

export default Producto;
